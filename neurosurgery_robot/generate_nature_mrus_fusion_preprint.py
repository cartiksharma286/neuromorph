#!/usr/bin/env python3
"""
Generate a Nature-style computational preprint for the MR/US fusion module.

All reported anatomical and registration results are generated by the synthetic
MR/US simulator and are not clinical validation data.
"""

from __future__ import annotations

import base64
import io
import os
from typing import Any, Dict

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
from matplotlib.backends.backend_pdf import PdfPages
from matplotlib.image import imread

from mrus_fusion_engine import MRUSFusionEngine


OUTPUT_FILENAME = "Nature_MRUS_Fusion_Prime_Moduli_Preprint.pdf"


def _add_header(fig: plt.Figure, title: str, page: int) -> None:
    fig.text(
        0.5,
        0.965,
        "Nature Portfolio | Computational Research Preprint",
        ha="center",
        fontsize=9,
        fontstyle="italic",
        color="#0369a1",
        fontweight="bold",
    )
    fig.text(0.5, 0.035, f"MR/US Fusion Prime-Moduli Preprint | Page {page} of 3",
             ha="center", fontsize=8, color="#64748b")
    fig.text(0.08, 0.925, title, ha="left", fontsize=15, fontweight="bold",
             color="#0f172a")


def _add_wrapped_text(fig: plt.Figure, x: float, y: float, text: str,
                      *, size: float = 8.5, color: str = "#334155") -> None:
    fig.text(x, y, text, va="top", ha="left", fontsize=size, color=color,
             wrap=True, linespacing=1.35)


def _run_reference_analysis() -> Dict[str, Any]:
    return MRUSFusionEngine(
        num_terms=14,
        seed_modulus=0.15,
        max_energy_j=6.0,
        dt_s=0.75,
        grid_dim=128,
    ).run_fusion_analysis(phase_rad=0.4, deformation_amp_mm=1.2)


def _page_one(pdf: PdfPages, result: Dict[str, Any]) -> None:
    fig = plt.figure(figsize=(8.5, 11), dpi=220)
    _add_header(
        fig,
        "Finite Prime-Moduli Elliptic Signatures for MR/US Fusion\n"
        "and Bounded Intraoperative Energy Envelopes",
        1,
    )
    fig.text(
        0.08, 0.862,
        "Cartik Sharma et al. | NeuroMorph Surgical Robotics",
        fontsize=9.2, color="#475569",
    )

    abstract = (
        "We describe a computational MR/US fusion demonstrator that co-registers "
        "synthetic pre-operative T2-weighted MR anatomy with a synthetic 8.5 MHz "
        "intraoperative ultrasound sector image. A finite recurrent sequence indexed "
        "by the first fourteen primes generates elliptic-integral signatures. The "
        "second-kind complete elliptic integral supplies an analytic energy corridor "
        "at every finite step. In the reference simulation (1.2 mm deformation "
        "amplitude, phase 0.4 rad), the model reports a target registration error "
        f"(TRE) of {result['fusion_quality']['target_registration_error_mm']:.3f} mm "
        f"and Dice coefficient of {result['fusion_quality']['dice_similarity_coefficient']:.4f}. "
        "These values are simulator outputs only; they do not establish clinical "
        "performance and require prospective phantom and patient-study validation."
    )
    fig.patches.append(plt.Rectangle((0.075, 0.715), 0.85, 0.12,
                                     transform=fig.transFigure, facecolor="#f8fafc",
                                     edgecolor="#cbd5e1", linewidth=1.0))
    fig.text(0.095, 0.812, "ABSTRACT", fontsize=9, fontweight="bold", color="#0369a1")
    _add_wrapped_text(fig, 0.095, 0.797, abstract, size=8.1)

    fig.text(0.08, 0.675, "1. Finite recurrent prime-moduli construction",
             fontsize=11, fontweight="bold", color="#0f172a")
    _add_wrapped_text(
        fig, 0.08, 0.645,
        "Let p_n denote the n-th prime, with n = 1, ..., N and N = 14. Starting "
        "from k_0 = 0.15, the bounded modulus is updated at each finite step:",
    )
    fig.text(0.5, 0.600,
             r"$k_n = \left(k_{n-1} + \frac{1}{p_n}\right)\,\mathrm{mod}\,1,"
             r"\quad 0 < k_n < 1,\quad p_n \in \{2,3,5,\ldots,43\}$",
             ha="center", fontsize=12, color="#075985")
    _add_wrapped_text(
        fig, 0.08, 0.562,
        "The complete elliptic integrals are evaluated with parameter m_n = k_n^2: "
        "K(k_n) = integral_0^(pi/2) [1 - k_n^2 sin^2(theta)]^(-1/2) dtheta and "
        "E(k_n) = integral_0^(pi/2) [1 - k_n^2 sin^2(theta)]^(1/2) dtheta.",
    )

    fig.text(0.08, 0.493, "2. Exact identity and finite energy bounds",
             fontsize=11, fontweight="bold", color="#0f172a")
    _add_wrapped_text(
        fig, 0.08, 0.463,
        "For k'_n = sqrt(1 - k_n^2), the numerical computation is audited using "
        "Legendre's relation. The model uses the monotonic interval 1 <= E(k_n) <= pi/2 "
        "to normalize energy without extrapolating outside this analytic bound.",
    )
    fig.text(0.5, 0.405,
             r"$E(k_n)K(k'_n) + E(k'_n)K(k_n) - K(k_n)K(k'_n) = \frac{\pi}{2}$",
             ha="center", fontsize=12, color="#075985")
    fig.text(0.5, 0.355,
             r"$e_n = E_{\max}\frac{E(k_n)}{\pi/2},\qquad "
             r"\frac{2}{\pi}E_{\max} \leq e_n \leq E_{\max}$",
             ha="center", fontsize=12, color="#075985")
    fig.text(0.5, 0.305,
             r"$\frac{2}{\pi}nE_{\max} \leq \sum_{i=1}^{n}e_i \leq nE_{\max},"
             r"\qquad n \in \{1,\ldots,14\}$",
             ha="center", fontsize=12, color="#075985")

    fig.text(0.08, 0.247, "3. Target-registration characterization",
             fontsize=11, fontweight="bold", color="#0f172a")
    _add_wrapped_text(
        fig, 0.08, 0.218,
        "The demonstrator reports a deterministic synthetic target-registration "
        "characteristic that rises with simulated displacement u: TRE = max(0.12, "
        "0.18 + 0.05||u|| + 100 mean(|Delta_Legendre|)) mm. Segmentation agreement is "
        "reported as a simulated Dice score. These equations define application "
        "behavior rather than a calibrated biophysical error model.",
    )
    fig.text(0.08, 0.095,
             "Disclosure: all images, anatomy, deformation, ultrasound speckle, and "
             "registration metrics in this preprint are computational simulations.",
             fontsize=8, color="#9f1239", fontweight="bold")
    pdf.savefig(fig, bbox_inches="tight")
    plt.close(fig)


def _page_two(pdf: PdfPages, result: Dict[str, Any]) -> None:
    fig, axes = plt.subplots(2, 2, figsize=(8.5, 11), dpi=220)
    fig.subplots_adjust(top=0.87, bottom=0.11, left=0.10, right=0.93, hspace=0.42, wspace=0.34)
    _add_header(fig, "Synthetic Dual-Modality Fusion and Finite Signature Plots", 2)

    chart_bytes = base64.b64decode(result["chart"].split(",", 1)[1])
    chart = imread(io.BytesIO(chart_bytes), format="png")
    axes[0, 0].imshow(chart)
    axes[0, 0].axis("off")
    axes[0, 0].set_title("a | Fusion engine composite output", fontsize=9, fontweight="bold", loc="left")

    rows = result["signature"]["rows"]
    n = np.array([row["index"] for row in rows])
    moduli = np.array([row["modulus_k"] for row in rows])
    k_vals = np.array([row["K_k"] for row in rows])
    e_vals = np.array([row["E_k"] for row in rows])
    ax = axes[0, 1]
    ax.plot(n, moduli, "o-", label=r"$k_n$", color="#0ea5e9")
    ax.plot(n, e_vals / (np.pi / 2.0), "s-", label=r"$E(k_n)/(\pi/2)$", color="#10b981")
    ax.set(xlabel="Finite step n", ylabel="Normalized value", ylim=(0, 1.05))
    ax.set_title("b | Prime-indexed modulus signature", fontsize=9, fontweight="bold", loc="left")
    ax.grid(True, linestyle=":", alpha=0.55)
    ax.legend(fontsize=7)

    energy = result["energy"]
    ax = axes[1, 0]
    ax.plot(n, energy["cumulative_floor_j"], "--", color="#f59e0b", label="Analytic floor")
    ax.plot(n, energy["cumulative_actual_j"], "o-", color="#0369a1", label="Elliptic-normalized energy")
    ax.plot(n, energy["cumulative_ceiling_j"], "--", color="#dc2626", label="Hard ceiling")
    ax.set(xlabel="Finite step n", ylabel="Cumulative energy (J)")
    ax.set_title("c | Bounded cumulative energy corridor", fontsize=9, fontweight="bold", loc="left")
    ax.grid(True, linestyle=":", alpha=0.55)
    ax.legend(fontsize=6.7)

    ax = axes[1, 1]
    ax.plot(n, k_vals, "o-", color="#7c3aed", label=r"$K(k_n)$")
    ax.plot(n, e_vals, "s-", color="#059669", label=r"$E(k_n)$")
    ax.set(xlabel="Finite step n", ylabel="Elliptic integral value")
    ax.set_title("d | Complete elliptic-integral characteristics", fontsize=9, fontweight="bold", loc="left")
    ax.grid(True, linestyle=":", alpha=0.55)
    ax.legend(fontsize=7)

    fig.text(
        0.10, 0.065,
        "Figure 1 | Simulated MR/iUS anatomy is rendered with MRI and ultrasound "
        "overlays, deformation vectors, and a corticospinal-tract safety corridor. "
        "Panels b-d use the finite N = 14 prime sequence and E_max = 6 J reference setting.",
        fontsize=8, color="#475569", wrap=True,
    )
    pdf.savefig(fig)
    plt.close(fig)


def _page_three(pdf: PdfPages, result: Dict[str, Any]) -> None:
    fig = plt.figure(figsize=(8.5, 11), dpi=220)
    _add_header(fig, "Reference Simulation Characteristics and Finite Audit Schedule", 3)
    quality = result["fusion_quality"]
    energy = result["energy"]
    signature = result["signature"]

    fig.text(0.08, 0.865, "Reference configuration", fontsize=11, fontweight="bold", color="#0f172a")
    characteristics = [
        ["MR modality", "Synthetic pre-operative T2-weighted structural image"],
        ["US modality", "Synthetic 8.5 MHz sector B-mode image with Rayleigh speckle"],
        ["Finite sequence", f"N = {signature['num_terms']}; seed k_0 = {signature['seed_modulus']:.2f}"],
        ["Deformation input", "1.2 mm amplitude; phase = 0.4 rad"],
        ["Pulse model", f"E_max = {energy['max_energy_j']:.1f} J; dt = {energy['dt_s']:.2f} s"],
        ["Synthetic TRE", f"{quality['target_registration_error_mm']:.3f} mm"],
        ["Synthetic Dice", f"{quality['dice_similarity_coefficient']:.4f}"],
        ["CST clearance", f"{quality['corticospinal_tract_clearance_mm']:.2f} mm"],
        ["Legendre max residual", f"{signature['max_legendre_residual']:.3e}"],
        ["Cumulative energy", f"{energy['total_cumulative_energy_j']:.3f} J / {energy['total_ceiling_energy_j']:.3f} J ceiling"],
    ]
    table = fig.add_axes([0.08, 0.570, 0.84, 0.265])
    table.axis("off")
    tbl = table.table(cellText=characteristics, colLabels=["Characteristic", "Reference value"],
                      colWidths=[0.28, 0.72], cellLoc="left", loc="center")
    tbl.auto_set_font_size(False)
    tbl.set_fontsize(8)
    tbl.scale(1, 1.45)
    for (row, col), cell in tbl.get_celld().items():
        cell.set_edgecolor("#cbd5e1")
        if row == 0:
            cell.set_facecolor("#e0f2fe")
            cell.set_text_props(weight="bold", color="#0c4a6e")
        elif row % 2:
            cell.set_facecolor("#f8fafc")

    fig.text(0.08, 0.525, "Finite prime-moduli audit schedule", fontsize=11, fontweight="bold", color="#0f172a")
    rows = [[
        str(r["index"]), str(r["prime"]), f"{r['modulus_k']:.4f}",
        f"{r['K_k']:.4f}", f"{r['E_k']:.4f}",
        f"{energy['per_step_bound_j'][i]:.3f}",
    ] for i, r in enumerate(signature["rows"])]
    audit = fig.add_axes([0.08, 0.175, 0.84, 0.315])
    audit.axis("off")
    audit_table = audit.table(
        cellText=rows,
        colLabels=["n", "p_n", "k_n", "K(k_n)", "E(k_n)", "e_n (J)"],
        colWidths=[0.09, 0.11, 0.17, 0.20, 0.20, 0.18],
        cellLoc="center",
        loc="center",
    )
    audit_table.auto_set_font_size(False)
    audit_table.set_fontsize(7.4)
    audit_table.scale(1, 1.18)
    for (row, _), cell in audit_table.get_celld().items():
        cell.set_edgecolor("#cbd5e1")
        if row == 0:
            cell.set_facecolor("#dbeafe")
            cell.set_text_props(weight="bold", color="#1e3a8a")
        elif row % 2:
            cell.set_facecolor("#f8fafc")
    fig.text(
        0.08, 0.09,
        "Reproducibility note: values are deterministically computed from the source "
        "fusion engine using SciPy complete elliptic integrals. The finite energy "
        "bound is an analytic property of the normalization; it is not a clinical "
        "dose authorization or a substitute for safety validation.",
        fontsize=8, color="#9f1239", wrap=True,
    )
    pdf.savefig(fig, bbox_inches="tight")
    plt.close(fig)


def generate_nature_mrus_fusion_preprint(
    output_filename: str = OUTPUT_FILENAME,
) -> str:
    """Generate the three-page PDF and return its absolute path."""
    output_path = os.path.join(os.path.dirname(os.path.abspath(__file__)), output_filename)
    result = _run_reference_analysis()
    with PdfPages(output_path) as pdf:
        _page_one(pdf, result)
        _page_two(pdf, result)
        _page_three(pdf, result)
    return output_path


if __name__ == "__main__":
    print(generate_nature_mrus_fusion_preprint())
